static volatile int volc_ark_vision_demo_running;
static volatile int volc_ark_vision_demo_started;

static unsigned char *volc_ark_vision_demo_read_file(const char *path, unsigned int *out_len)
{
    FILE *fd;
    unsigned char *buf;
    int len;
    int rlen;

    if (!path || !out_len) {
        return NULL;
    }

    *out_len = 0;
    fd = fopen(path, "r");
    if (!fd) {
        printf("[volc_ark] image open failed: %s\n", path);
        return NULL;
    }

    len = flen(fd);
    if (len <= 0) {
        printf("[volc_ark] invalid image len: %d\n", len);
        fclose(fd);
        return NULL;
    }

    printf("[volc_ark] image len: %d\n", len);
    buf = (unsigned char *)volc_ark_vision_demo_malloc_large(len);
    if (!buf) {
        printf("[volc_ark] image malloc failed: %d\n", len);
        fclose(fd);
        return NULL;
    }

    memset(buf, 0, len);

    rlen = fread(buf, len, 1, fd);
    fclose(fd);
    if (rlen != len) {
        printf("[volc_ark] image read failed: %d/%d\n", rlen, len);
        volc_ark_vision_demo_free_large(buf);
        return NULL;
    }

    *out_len = (unsigned int)len;
    return buf;
}

static void volc_ark_vision_print_result(const char *tag, int ret, struct ai_vision_result *result)
{
    if (ret == AI_OK) {
        printf("[%s] result: %s\n", tag, result->text ? result->text : "");
        return;
    }

    printf("[%s] request failed: %d\n", tag, ret);
    if (result->text) {
        printf("[%s] error: %s\n", tag, result->text);
    }
    if (result->raw_json) {
        printf("[%s] raw: %s\n", tag, result->raw_json);
    }
}

static int volc_ark_vision_recognize(const struct ai_image_input *image,
                                     const char *provider_params,
                                     const char *prompt,
                                     const char *tag)
{
    struct ai_config ai_cfg;
    struct ai_client *client = NULL;
    struct ai_vision_result result = {0};
    int ret;

    if (!VOLC_ARK_API_KEY[0]) {
        printf("[volc_ark] missing VOLC_ARK_API_KEY\n");
        return AI_ERR_PARAM;
    }

    memset(&ai_cfg, 0, sizeof(ai_cfg));
    ai_cfg.provider_name = "volc_ark";
    ai_cfg.api_key = VOLC_ARK_API_KEY;
    ai_cfg.provider_params = provider_params;
    ai_cfg.timeout_ms = 30000;
    ai_cfg.http_backend = AI_HTTP_BACKEND_CURL;

    ret = ai_client_create(&ai_cfg, &client);
    if (ret != AI_OK) {
        printf("[%s] ai_client_create failed: %d\n", tag, ret);
        return ret;
    }

    ret = ai_vision_recognize(client, image, prompt ? prompt : VOLC_ARK_PROMPT, &result);
    volc_ark_vision_print_result(tag, ret, &result);

    ai_vision_result_free(&result);
    ai_client_destroy(client);
    return ret;
}

int volc_ark_vision_recognize_buffer(const unsigned char *jpeg_data, unsigned int jpeg_len, const char *prompt)
{
    struct ai_image_input image;

    if (!jpeg_data || !jpeg_len) {
        return AI_ERR_PARAM;
    }

    memset(&image, 0, sizeof(image));
    image.format = AI_IMAGE_JPEG;
    image.data = jpeg_data;
    image.size = jpeg_len;

    return volc_ark_vision_recognize(&image, NULL, prompt, "volc-ark-buffer");
}

static void volc_ark_vision_url_demo_task(void *priv)
{
    (void)priv;

    volc_ark_vision_recognize(NULL,
                              VOLC_ARK_URL_PROVIDER_PARAMS,
                              VOLC_ARK_PROMPT,
                              "volc-ark-url");

    volc_ark_vision_demo_running = 0;
    volc_ark_vision_demo_started = 0;
}

static void volc_ark_vision_file_demo_task(void *priv)
{
    struct ai_image_input image;
    unsigned char *image_data = NULL;
    unsigned int image_len = 0;

    (void)priv;

    memset(&image, 0, sizeof(image));
    image_data = volc_ark_vision_demo_read_file(VOLC_ARK_IMAGE_PATH, &image_len);
    if (image_data) {
        image.format = AI_IMAGE_JPEG;
        image.data = image_data;
        image.size = image_len;
        volc_ark_vision_recognize(&image, NULL, VOLC_ARK_PROMPT, "volc-ark-file");
    }

    volc_ark_vision_demo_free_large(image_data);
    volc_ark_vision_demo_running = 0;
    volc_ark_vision_demo_started = 0;
}

static void volc_ark_vision_builtin_demo_task(void *priv)
{
    (void)priv;

    printf("[volc_ark] builtin jpeg len: %u\n", (unsigned int)sizeof(volc_ark_builtin_jpeg));
    volc_ark_vision_recognize_buffer(volc_ark_builtin_jpeg,
                                     (unsigned int)sizeof(volc_ark_builtin_jpeg),
                                     VOLC_ARK_PROMPT);

    volc_ark_vision_demo_running = 0;
    volc_ark_vision_demo_started = 0;
}

static void volc_ark_vision_demo_start_task(void (*task)(void *), const char *name)
{
    int ret;

    if (volc_ark_vision_demo_started) {
        printf("[volc_ark] vision demo already started\n");
        return;
    }
    if (volc_ark_vision_demo_running) {
        printf("[volc_ark] vision demo already running\n");
        return;
    }

    volc_ark_vision_demo_started = 1;
    volc_ark_vision_demo_running = 1;
    ret = thread_fork(name, 20, 4 * 1024, 0, 0, task, NULL);
    if (ret != OS_NO_ERR) {
        volc_ark_vision_demo_started = 0;
        volc_ark_vision_demo_running = 0;
        printf("[volc_ark] thread_fork failed: %d\n", ret);
    }
}

void volc_ark_vision_url_demo_start(void)
{
    volc_ark_vision_demo_start_task(volc_ark_vision_url_demo_task, "volc_ark_url_demo");
}

void volc_ark_vision_file_demo_start(void)
{
    volc_ark_vision_demo_start_task(volc_ark_vision_file_demo_task, "volc_ark_file_demo");
}

void volc_ark_vision_builtin_demo_start(void)
{
    volc_ark_vision_demo_start_task(volc_ark_vision_builtin_demo_task, "volc_ark_builtin_demo");
}

